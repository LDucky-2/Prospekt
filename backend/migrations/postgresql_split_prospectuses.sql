BEGIN;

ALTER TYPE activityaction ADD VALUE IF NOT EXISTS 'prospectus_created';
ALTER TYPE activityaction ADD VALUE IF NOT EXISTS 'prospectus_updated';
ALTER TYPE activityaction ADD VALUE IF NOT EXISTS 'prospectus_deleted';

CREATE TABLE prospectus (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id INTEGER NOT NULL REFERENCES university(id) ON DELETE CASCADE,
    session VARCHAR(20) NOT NULL,
    overview VARCHAR(2000) NOT NULL,
    application_start DATE,
    application_end DATE,
    admit_card_download DATE,
    exam_date DATE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

INSERT INTO prospectus
    (id, university_id, session, overview, application_start, application_end,
     admit_card_download, exam_date, created_at, updated_at)
SELECT id, id, session, overview, application_start, application_end,
       admit_card_download, exam_date, created_at, updated_at
FROM university;

SELECT setval(
    pg_get_serial_sequence('prospectus', 'id'),
    COALESCE(MAX(id), 1),
    COALESCE(MAX(id) IS NOT NULL, FALSE)
)
FROM prospectus;

ALTER TABLE unit ADD COLUMN prospectus_id INTEGER;
UPDATE unit SET prospectus_id = university_id;
ALTER TABLE unit ALTER COLUMN prospectus_id SET NOT NULL;
ALTER TABLE unit
    ADD CONSTRAINT unit_prospectus_id_fkey
    FOREIGN KEY (prospectus_id) REFERENCES prospectus(id) ON DELETE CASCADE;
ALTER TABLE unit DROP COLUMN university_id;

CREATE INDEX ix_prospectus_university_id ON prospectus (university_id);
CREATE INDEX ix_unit_prospectus_id ON unit (prospectus_id);

COMMIT;
